"""RESULTS.md rendering - the report the decision is read from.

Follows docs/EXPERIMENT.md §12: manifest, primary contrast, McNemar,
descriptive distributions, error-code table, threats, verdict, and the exact
commands that regenerate every number.
"""

from __future__ import annotations

from typing import Dict, List, Optional

from .harness import _percentile, _median


def _fmt(value, dash: str = "n/a") -> str:
    return dash if value is None else str(value)


def _histogram(values: List[int], width: int = 40) -> str:
    if not values:
        return "_no data_"
    low, high = min(values), max(values)
    if low == high:
        return f"all {low}"
    buckets = 10
    span = (high - low) / buckets
    counts = [0] * buckets
    for value in values:
        index = min(buckets - 1, int((value - low) / span)) if span else 0
        counts[index] += 1
    peak = max(counts) or 1
    lines = []
    for index, count in enumerate(counts):
        lo = low + index * span
        hi = lo + span
        bar = "#" * round(count / peak * width)
        lines.append(f"  {lo:5.0f}-{hi:5.0f} | {bar} {count}")
    return "\n".join(lines)


def render_results(report: Dict) -> str:
    arms = report["arms"]
    control = arms["control"]
    treatment = arms.get("treatment")
    contrast = report.get("contrast", {})
    manifest = report.get("manifest", {})
    per_task = report.get("per_task", {})

    lines: List[str] = []
    lines.append("# RESULTS")
    lines.append("")
    lines.append("Generated by `python -m imprimatur_eval ab` - see §Reproduction.")
    lines.append("")

    lines.append("## 1. Manifest")
    lines.append("")
    lines.append("| Field | Value |")
    lines.append("| --- | --- |")
    for key, value in manifest.items():
        lines.append(f"| {key} | {value} |")
    lines.append(
        "| protocol | docs/EXPERIMENT.md (frozen; SHA-256 recorded below) |"
    )
    lines.append("")

    lines.append("## 2. Primary contrast - tokens per correct document")
    lines.append("")
    lines.append("| Arm | Compile rate | Tokens | **Tokens per correct doc** |")
    lines.append("| --- | --- | --- | --- |")
    lines.append(
        f"| control (single shot) | {control['compile_rate']:.2f} "
        f"| {control['tokens']} | **{_fmt(control['tokens_per_correct_doc'])}** |"
    )
    if treatment:
        lines.append(
            f"| treatment (oracle loop) | {treatment['compile_rate']:.2f} "
            f"| {treatment['tokens']} | **{_fmt(treatment['tokens_per_correct_doc'])}** |"
        )
    if "ablation" in arms:
        ablation = arms["ablation"]
        lines.append(
            f"| ablation (best-of-k) | {ablation['compile_rate']:.2f} "
            f"| {ablation['tokens']} | **{_fmt(ablation['tokens_per_correct_doc'])}** |"
        )
    lines.append("")
    lines.append(
        f"**R = C_treatment / C_control = {_fmt(contrast.get('ratio_R'))}** "
        f"(95% CI {_fmt(contrast.get('ci95'))}; R < 1 favours the oracle)"
    )
    lines.append("")
    lines.append(f"**Decision verdict: {contrast.get('verdict', 'n/a')}**")
    lines.append("")

    lines.append("## 3. Secondary - McNemar on paired correctness")
    lines.append("")
    mcnemar = contrast.get("mcnemar", {})
    lines.append("| Both correct | Control only | Treatment only | Neither |")
    lines.append("| --- | --- | --- | --- |")
    lines.append(
        f"| {mcnemar.get('both_correct', 0)} "
        f"| {mcnemar.get('control_only', 0)} "
        f"| {mcnemar.get('treatment_only', 0)} "
        f"| {mcnemar.get('neither', 0)} |"
    )
    lines.append("")

    lines.append("## 4. Descriptive")
    lines.append("")
    if treatment:
        lines.append(
            f"- Iterations to green: mean "
            f"{_fmt(treatment['mean_iterations'])} "
            f"(median {_fmt(_median([r['iterations'] for r in per_task['treatment'] if r['iterations'] is not None]))}, "
            f"p90 {_fmt(_percentile([r['iterations'] for r in per_task['treatment'] if r['iterations'] is not None], 90))})"
        )
        touched = [
            r["lines_touched"]
            for r in per_task["treatment"]
            if r["lines_touched"] is not None
        ]
        lines.append(
            f"- Lines touched per repair: median {_fmt(_median(touched))}, "
            f"p90 {_fmt(_percentile(touched, 90))}"
        )
        lines.append("")
        lines.append("```")
        lines.append(_histogram(touched))
        lines.append("```")
        lines.append("")
    else:
        lines.append("- Treatment arm not run.")
        lines.append("")

    lines.append("Error-code distribution (failures only):")
    lines.append("")
    lines.append("| Arm | Codes |")
    lines.append("| --- | --- |")
    for name, arm in arms.items():
        codes = arm["error_codes"]
        rendered = ", ".join(f"{code}x{count}" for code, count in codes.items())
        lines.append(f"| {name} | {rendered or 'none'} |")
    lines.append("")

    lines.append("## 5. Threats and limitations")
    lines.append("")
    lines.append(
        "- **Construct:** the dependent variable is *compiles*, which is "
        "necessary but not sufficient for correctness. This experiment "
        "measures **well-formedness, not content quality**."
    )
    lines.append(
        "- **Tokens as cost:** a proxy. Excludes latency, transport retries "
        "and human review time."
    )
    lines.append(
        "- **Prompt confound is the treatment:** Arm B sees diagnostics and "
        "Arm A does not, by design; both share the base prompt."
    )
    lines.append(
        "- **External validity:** one model family, English intents, "
        "HTML-shaped documents."
    )
    if manifest.get("model") == "stub":
        lines.append(
            "- **This run used the deterministic stub model, which is plumbing "
            "only and excluded from reported results (protocol §5.3). The "
            "numbers above prove the harness works, not that the oracle pays."
        )
    lines.append("")

    lines.append("## 6. Verdict")
    lines.append("")
    verdict = contrast.get("verdict", "n/a")
    if manifest.get("model") == "stub":
        lines.append(
            f"Harness verdict on stub data: **{verdict}**. This is a plumbing "
            "result: the stub is designed to fail and converge, so the numbers "
            "exercise every code path and carry no claim about real models. "
            "Re-run with a real model (see §Reproduction) for the decision."
        )
    else:
        lines.append(
            f"**{verdict}.** R = {_fmt(contrast.get('ratio_R'))} with 95% CI "
            f"{_fmt(contrast.get('ci95'))}. Per the pre-registered rule: "
            "SUPPORT (R<=0.80, upper CI<1.00) ships htvl-mcp; REFUTE "
            "(R>=1.20, lower CI>1.00) does not; otherwise INCONCLUSIVE is "
            "published as a null result."
        )
    lines.append("")

    lines.append("## 7. Reproduction")
    lines.append("")
    lines.append("```bash")
    lines.append(
        f"python -m imprimatur_eval build --out data.jsonl "
        f"--model {manifest.get('model', 'stub')}"
    )
    lines.append(
        "python -m imprimatur_eval repair --in data.jsonl "
        "--out traces.jsonl --sft-out sft.jsonl"
    )
    lines.append(
        f"python -m imprimatur_eval ab --model {manifest.get('model', 'stub')} "
        f"--report RESULTS.md"
    )
    lines.append("```")
    lines.append("")
    return "\n".join(lines)
